from pylatex import Document, Section, Subsection, Command
from pylatex.utils import NoEscape
from datetime import datetime, timedelta

# Sample events (room, event, start time, end time)
events = [
    {"room": "Room 1", "event": "Team Meeting", "start": "2025-11-05 09:00", "end": "2025-11-05 09:45"},
    {"room": "Room 2", "event": "Client Call", "start": "2025-11-05 10:00", "end": "2025-11-05 10:30"},
    {"room": "Room 3", "event": "Workshop", "start": "2025-11-05 13:00", "end": "2025-11-05 14:15"},
    {"room": "Room 4", "event": "Presentation", "start": "2025-11-05 14:00", "end": "2025-11-05 15:00"},
    {"room": "Room 5", "event": "Team Brainstorming", "start": "2025-11-05 09:30", "end": "2025-11-05 10:30"}
]

# Function to convert time to row (for 5-minute intervals)
def time_to_row(time_str):
    """Converts a time string like '09:10' to a row number in a 5-minute grid"""
    time_obj = datetime.strptime(time_str, '%H:%M')
    start_time = datetime.strptime("09:00", '%H:%M')
    delta_minutes = (time_obj - start_time).seconds // 60
    return delta_minutes // 5  # 5-minute intervals

# Generate the LaTeX document with schedule
def generate_schedule_pdf(events):
    # Create a new LaTeX document
    doc = Document()

    # Add title
    doc.preamble.append(Command('title', 'Room Schedule'))
    doc.preamble.append(Command('author', 'Generated by PyLaTeX'))
    doc.append(NoEscape(r'\maketitle'))

    # Create the table for the schedule
    rooms = ["Room 1", "Room 2", "Room 3", "Room 4", "Room 5"]
    time_slots = [f"{i:02}:{j:02}" for i in range(9, 18) for j in range(0, 60, 5)]  # Times from 09:00 to 17:55 in 5-min intervals

    # Create table headers (rooms)
    table_data = []
    table_data.append(["Time"] + rooms)

    # Initialize an empty table with all cells empty
    schedule = {room: [""] * len(time_slots) for room in rooms}
    multirow_cells = {}  # To track multirow cells

    # Populate the schedule with events
    for event in events:
        start_row = time_to_row(event["start"][11:16])
        end_row = time_to_row(event["end"][11:16])
        room_idx = rooms.index(event["room"])  # Find the column for the room
        
        # For the first row of the event, store the event name in the table
        for row_idx in range(start_row, end_row + 1):
            if row_idx == start_row:
                schedule[rooms[room_idx]][row_idx] = event["event"]
                multirow_cells[(room_idx, row_idx)] = (end_row - start_row + 1)  # Store how many rows to span

    # Populate table with time slots and event data
    for i, time_slot in enumerate(time_slots):
        row = [time_slot] + [schedule[room][i] for room in rooms]
        table_data.append(row)

    # Build LaTeX table
    with doc.create(Section('Schedule')):
        with doc.create(Subsection('Room Schedule for 2025-11-05')):
            doc.append(r'\begin{tabular}{|c|' + 'c|' * len(rooms) + '}')
            doc.append(r'\hline')  # Horizontal line at the top of the table
            for i, row in enumerate(table_data):
                row_cells = []
                for j, cell in enumerate(row):
                    if cell:  # If the cell contains an event name
                        if i == 0:  # Header row (time slots)
                            row_cells.append(f'{cell}')
                        else:
                            if (j - 1, i - 1) in multirow_cells:  # Check if this cell has a multirow
                                span_count = multirow_cells[(j - 1, i - 1)]
                                row_cells.append(f'\\multirow{{{span_count}}}{{*}}{{{cell}}}')
                                multirow_cells.pop((j - 1, i - 1))  # Remove from tracking after it has been used
                            else:
                                row_cells.append('')
                    else:
                        row_cells.append('')
                doc.append(' & '.join(row_cells) + r' \\')  # Add row data
                doc.append(r'\hline')  # Horizontal line after each row
            doc.append(r'\end{tabular}')
            doc.append("\n")

    # Generate the PDF
    doc.generate_pdf("room_schedule_5min", clean_tex=False)

# Generate the schedule PDF
generate_schedule_pdf(events)

print("PDF created successfully!")
